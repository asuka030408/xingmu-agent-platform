CREATE TABLE IF NOT EXISTS company (
    id integer PRIMARY KEY,
    name text NOT NULL,
    description text NOT NULL
);

CREATE TABLE IF NOT EXISTS warehouses (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code text NOT NULL UNIQUE,
    name text NOT NULL,
    city text NOT NULL
);

CREATE TABLE IF NOT EXISTS equipment_models (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code text NOT NULL UNIQUE,
    name text NOT NULL,
    category text NOT NULL,
    external_rental_cost integer NOT NULL CHECK (external_rental_cost >= 0)
);

CREATE TABLE IF NOT EXISTS substitutions (
    requested_model_id integer NOT NULL REFERENCES equipment_models(id),
    substitute_model_id integer NOT NULL REFERENCES equipment_models(id),
    premium_cost integer NOT NULL CHECK (premium_cost >= 0),
    PRIMARY KEY (requested_model_id, substitute_model_id)
);

CREATE TABLE IF NOT EXISTS assets (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    asset_code text NOT NULL UNIQUE,
    model_id integer NOT NULL REFERENCES equipment_models(id),
    warehouse_id integer NOT NULL REFERENCES warehouses(id),
    status text NOT NULL CHECK (status IN ('active', 'retired'))
);

CREATE TABLE IF NOT EXISTS projects (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code text NOT NULL UNIQUE,
    name text NOT NULL,
    city text NOT NULL,
    venue text NOT NULL,
    status text NOT NULL CHECK (status IN ('draft', 'confirmed')),
    starts_at timestamp NOT NULL,
    ends_at timestamp NOT NULL,
    prep_hours integer NOT NULL DEFAULT 6,
    return_hours integer NOT NULL DEFAULT 4,
    priority integer NOT NULL DEFAULT 1,
    CHECK (ends_at > starts_at)
);

CREATE TABLE IF NOT EXISTS requirements (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id integer NOT NULL REFERENCES projects(id) ON DELETE CASCADE,
    model_id integer NOT NULL REFERENCES equipment_models(id),
    quantity integer NOT NULL CHECK (quantity > 0),
    UNIQUE (project_id, model_id)
);

CREATE TABLE IF NOT EXISTS reservations (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id integer NOT NULL REFERENCES projects(id) ON DELETE CASCADE,
    asset_id integer NOT NULL REFERENCES assets(id),
    reserved_from timestamp NOT NULL,
    reserved_until timestamp NOT NULL,
    CHECK (reserved_until > reserved_from)
);

CREATE TABLE IF NOT EXISTS maintenance (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    asset_id integer NOT NULL REFERENCES assets(id),
    starts_at timestamp NOT NULL,
    ends_at timestamp NOT NULL,
    reason text NOT NULL,
    CHECK (ends_at > starts_at)
);

CREATE TABLE IF NOT EXISTS transfer_routes (
    from_warehouse_id integer NOT NULL REFERENCES warehouses(id),
    to_city text NOT NULL,
    lead_hours integer NOT NULL CHECK (lead_hours >= 0),
    cost_per_asset integer NOT NULL CHECK (cost_per_asset >= 0),
    PRIMARY KEY (from_warehouse_id, to_city)
);

CREATE INDEX IF NOT EXISTS ix_projects_starts_at ON projects(starts_at);
CREATE INDEX IF NOT EXISTS ix_reservations_asset_window ON reservations(asset_id, reserved_from, reserved_until);
CREATE INDEX IF NOT EXISTS ix_maintenance_asset_window ON maintenance(asset_id, starts_at, ends_at);

-- The database rejects overlapping confirmed bookings even under concurrent requests.
CREATE EXTENSION IF NOT EXISTS btree_gist;
ALTER TABLE reservations ADD COLUMN IF NOT EXISTS requirement_id integer REFERENCES requirements(id);
ALTER TABLE reservations ADD COLUMN IF NOT EXISTS request_key uuid;
CREATE UNIQUE INDEX IF NOT EXISTS uq_reservations_request_key ON reservations(request_key) WHERE request_key IS NOT NULL;
DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'reservations_no_overlap') THEN
        ALTER TABLE reservations ADD CONSTRAINT reservations_no_overlap
        EXCLUDE USING gist (asset_id WITH =, tsrange(reserved_from, reserved_until, '[)') WITH &&);
    END IF;
END $$;

CREATE TABLE IF NOT EXISTS booking_audit (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_key uuid NOT NULL,
    action text NOT NULL,
    outcome text NOT NULL,
    project_code text NOT NULL,
    asset_code text NOT NULL,
    detail text NOT NULL DEFAULT '',
    created_at timestamptz NOT NULL DEFAULT now()
);
